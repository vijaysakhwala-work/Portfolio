// Finds the pictures you have added and lists them in src/lib/images.gen.js. Run automatically before dev and build.
// Convention (the file name, without its extension, is the key):
//   public/images/shots/<key>.(webp|png|jpg|jpeg|avif)       service, AI and work screenshots: svc-web, ai-ai-assistants, work-haven ...
//   public/images/industries/<slug>.(webp|png|jpg|jpeg|avif)  industry photos: healthcare, ecommerce, real-estate ...
//   public/images/people/<key>.(webp|png|jpg|jpeg|avif)       people: founder
// Anything you do not add stays an empty image holder.
import fs from 'node:fs/promises';
import path from 'node:path';

const EXT = /\.(webp|png|jpe?g|avif)$/i;
const found = {};
async function scan(dir, prefix) {
  let names = [];
  try { names = await fs.readdir(path.join('public/images', dir)); } catch { return; }
  for (const n of names.sort()) if (EXT.test(n)) found[prefix + n.replace(EXT, '')] = `/images/${dir}/${n}`;
}
await scan('shots', '');
await scan('industries', 'industry-');
await scan('people', '');
await fs.mkdir('src/lib', { recursive: true });
await fs.writeFile('src/lib/images.gen.js', `// GENERATED by scripts/scan-images.mjs. Do not edit; add files under public/images/{shots,industries,people} instead.\nexport const FOUND = ${JSON.stringify(found, null, 2)};\n`);
console.log(`Found ${Object.keys(found).length} picture(s); everything else shows an image holder.`);
