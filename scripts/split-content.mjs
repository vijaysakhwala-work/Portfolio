// Splits the hand-written content into a light index (always shipped) and one lazy chunk per page (shipped only for that page).
// Writes src/content/gen/*. Run automatically before dev and build; safe to run any time.
import fs from 'node:fs/promises';
import {serviceFull,postsFull} from '../src/content/sources.js';
import {wordCount,readMinutes} from '../src/content/text.js';

const dir='src/content/gen';
await fs.rm(dir,{recursive:true,force:true});
await fs.mkdir(dir,{recursive:true});
const pick=(o,keys)=>Object.fromEntries(keys.filter(k=>o[k]!==undefined).map(k=>[k,o[k]]));
const js=(banner,exp,value)=>`// ${banner}\nexport ${exp} = ${JSON.stringify(value)};\n`;
const HEADER='GENERATED by scripts/split-content.mjs from src/content/*.js. Do not edit.';

const postLight=['slug','title','seoTitle','metaDescription','keyword','keywords','category','published','updated','summary','cover','services'];
await fs.writeFile(`${dir}/posts-light.js`,js(HEADER,'const postsLight',postsFull.map(p=>({...pick(p,postLight),words:wordCount(p),minutes:readMinutes(p)}))));
for(const p of postsFull)await fs.writeFile(`${dir}/post-${p.slug}.js`,js(HEADER,'default',pick(p,['takeaways','body','faq'])).replace('export default =','export default'));

const light={};
for(const [slug,s] of Object.entries(serviceFull)){
  light[slug]={...pick(s,['seoTitle','metaDescription','keyword','aiOneLiner']),subs:Object.fromEntries(Object.entries(s.subs).map(([k,x])=>[k,pick(x,['seoTitle','metaDescription','keyword'])]))};
  await fs.writeFile(`${dir}/svc-${slug}.js`,js(HEADER,'default',s).replace('export default =','export default'));
}
await fs.writeFile(`${dir}/services-light.js`,js(HEADER,'const serviceLight',light));

const loaders=`// ${HEADER}\nexport const postLoaders = {\n${postsFull.map(p=>`  '${p.slug}': () => import('./post-${p.slug}.js'),`).join('\n')}\n};\nexport const svcLoaders = {\n${Object.keys(serviceFull).map(k=>`  '${k}': () => import('./svc-${k}.js'),`).join('\n')}\n};\n`;
await fs.writeFile(`${dir}/loaders.js`,loaders);
console.log(`Split ${postsFull.length} posts and ${Object.keys(serviceFull).length} services into ${dir}/`);
