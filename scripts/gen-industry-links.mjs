// Writes src/industry-service-links.js: which industry pages feature each service (from the industry pages' own service cards).
// The file is small on purpose so service and article pages do not download the whole industry module.
import fs from 'node:fs';
import {industryContent} from '../src/industry-content.js';
export function industryServiceMap(){const map={};for(const [slug,content] of Object.entries(industryContent))for(const [,,href] of content.cards){const key=href.replace(/\/$/,'');(map[key]=map[key]||[]);if(!map[key].includes(slug))map[key].push(slug)}return map}
if(process.argv[1]&&process.argv[1].endsWith('gen-industry-links.mjs')){
 fs.writeFileSync('src/industry-service-links.js','// Generated by scripts/gen-industry-links.mjs from src/industry-content.js. Do not edit by hand.\nexport const industryServiceLinks='+JSON.stringify(industryServiceMap())+';\n');
 console.log('Wrote src/industry-service-links.js');
}
